/**
 * 역할 — **단일 출처.**
 *
 * ★ 왜 파일이 따로 있는가:
 *   역할 목록과 한국어 이름이 **네 곳에 복사**돼 있었고, 그중 하나
 *   (`loadoutAnalysis.js:ROLE_ORDER`)에 `FLYER` 가 빠져 있었다.
 *   그 사본을 쓰는 화면이 편성 화면이라, **마법 요정과 결연한 천사가
 *   편성 목록에 아예 나타나지 않았다** — 헤더는 "보유 동료 25종"인데
 *   실제로 그려지는 카드는 23장이었다. 가챠로 뽑아도 쓸 수 없는 유닛이었다.
 *
 *   같은 사실이 두 곳에 적히면 언젠가 갈라진다. 이 저장소가 반복해서 겪은
 *   실패 형태이므로(추천 편성 · `enemyScale` · 가챠 확률), 역할도 한 곳으로 모은다.
 *
 * ★ 순서는 **전열 → 후열**이다. 편성 화면·도감·분석 패널이 전부 이 순서를 쓴다.
 *   순서를 바꾸면 세 화면이 같이 바뀐다 — 그게 단일 출처의 요점이다.
 *
 * ★ 새 역할을 units.json 에 추가하면 `roles.test.js` 가 깨진다.
 *   그래야 "데이터에는 있는데 화면에는 없는 역할"이 다시 생기지 않는다.
 */

// ★ '공중에 닿는가'는 전투 규칙이다 — 사본을 만들면 화면과 시뮬이 갈라진다.
import { canHitFlying } from "./combat.js";
import { tagsToMask } from "./tags.js";
// ★ 역할 **이름**은 `i18n/messages/terms.json` 이 두 언어로 갖는다 (2026-08-07).
//   여기 있는 것은 id 목록과 전투 규칙이지 글자가 아니다.
import { t } from "../../i18n/index.js";

/** 표시 순서 (전열 → 후열) */
export const ROLE_ORDER = [
    "BLOCKER",
    "MELEE",
    "RANGED",
    "CASTER",
    "SUPPORT",
    "SIEGE",
    "FLYER",
];

/**
 * 역할 이름. UI 는 이것만 쓴다 — 화면마다 다른 단어를 쓰면 같은 역할이 달라 보인다.
 *
 * ★★ **함수여야 한다.** 상수 객체는 모듈 로드 시 한 번 계산되므로 설정에서 언어를
 *   바꿔도 값이 바뀌지 않는다. 글자의 출처는 `terms.json:role.*` 이고, 여기 없는
 *   역할은 `t()` 가 키(`terms.role.FOO`)를 그대로 돌려준다 — 조용히 비는 것보다 낫다.
 */
export function roleLabel(role, lang) {
    return t(`terms.role.${role}`, undefined, lang);
}

/*
 * ★★★ `ROLE_LABEL_KO` 상수는 **지웠다** (2026-08-07). 상수 객체는 모듈 로드 시
 *   한 번 계산되므로 설정에서 언어를 바꿔도 값이 바뀌지 않고, 그 사실을 아무것도
 *   알려 주지 않는다 — 화면 다섯이 전부 `roleLabel(role)` 로 옮겨졌다.
 *   별칭을 남기면 다음 호출부가 그것을 쓴다 (이 저장소의 규약).
 */

/**
 * **적을 죽일 수 있는** 역할.
 *
 * ★ 방벽과 근접은 붙잡은 것만 때린다. 뒤에서 화력을 내는 역할이 하나도 없으면
 *   "막기만 하고 죽이지 못하는" 편성이 된다 — 편성 분석의 CRITICAL 판정 기준이다.
 * ★ FLYER 가 빠져 있어서, 비행 화력으로 짠 편성이 "후열 화력 없음"으로
 *   오탐되고 fitness 가 -35 깎였다.
 */
export const BACKLINE_ROLES = ["RANGED", "CASTER", "SIEGE", "FLYER"];

/**
 * **발사체로 때리는 역할** — 나머지는 전부 즉발이다.
 *
 * ★★ 이 사실은 오래도록 `engage.js` 안의 private const 하나였고, `validate-data.mjs`
 *   가 같은 목록을 손으로 한 번 더 적고 있었다. 그 사본은 아군만 검사했기 때문에
 *   **적 11종이 사거리 190 을 들고 즉발로 때리는 것**을 아무도 잡지 못했다
 *   (`enemies.json` 에 role 이 아예 없어 62/62 가 MELEE 로 정규화됐다).
 *   지금은 전투·검사기가 같은 값을 본다.
 *
 * ★★★ **FLYER 도 쏜다** (2026-08-05). 적 쪽을 고치고 나서도 아군 비행 4종은
 *   사거리 160–200 을 들고 **화면을 가로질러 즉발로** 때리고 있었다 — 적 11종과
 *   정확히 같은 결함인데, 상수가 아군·적을 함께 보게 된 뒤에도 목록에 FLYER 가
 *   없어서 그대로 남았다. 비행은 정의상 후열이고(`BACKLINE_ROLES`) 실제 사거리도
 *   160–200 으로 원거리 무리 한가운데다. **개체별이 아니라 역할 단위로** 넣는다 —
 *   개체별로 정하면 "왜 이 비행은 쏘고 저 비행은 안 쏘는가"의 답이 데이터 어디에도
 *   남지 않고, 새 비행 동료가 조용히 즉발로 태어난다.
 *
 * ★ **SUPPORT 는 넣지 않는다.** 사거리 190–235 로 경계를 넘지만 `engage.js` 의
 *   `trySupport` 는 `tryAttack` 을 지나지 않는다 — 여기 적어도 한 발도 쏘지 않는
 *   **죽은 선언**이 될 뿐이다. 지원은 피해가 아니라 힐이라 "즉발이 부당한가"라는
 *   질문 자체가 성립하지 않는다. 검사기도 같은 이유로 SUPPORT 만 사거리 대조에서 뺀다.
 *
 * ★ 객체인 이유는 `engage.js:tryAttack` 이 매 공격마다 조회하기 때문이다 —
 *   배열 `includes` 는 그 자리에서 선형 탐색이 된다.
 */
export const PROJECTILE_ROLES = { RANGED: 1, CASTER: 1, SIEGE: 1, FLYER: 1 };

/** 이 역할은 발사체를 쏘는가 (= 피해가 도착하기까지 이동 시간이 있는가) */
export function usesProjectile(role) {
    return PROJECTILE_ROLES[role] === 1;
}

/**
 * 이 동료가 **공중에 닿는가** (2026-08-05, 사용자 제보).
 *
 * ★★ 제보: "원거리 · 시전 이 정도로만 적혀 있으면 이게 공중 요격이 가능한지
 *   헷갈린다." 실제로 역할은 **대공 여부와 무관하다** — 물리 원거리는 못 닿고,
 *   술식 원거리는 닿는다. 같은 '원거리'인데 답이 갈린다.
 *
 * ★ 판정은 전투 규칙 모듈이 한다 (`combat.js:canHitFlying`). 화면이 "술식이면
 *   되겠지" 같은 사본 규칙을 갖는 순간, 시뮬이 규칙을 바꿔도 화면은 옛 답을
 *   계속 말한다 — 추천 편성이 5-15 에서 정확히 그 사고를 냈다.
 *
 * @param {{tags?: string[], dmgType: string}} def units.json 의 정의
 */
export function unitHitsAir(def) {
    if (!def) return false;
    return canHitFlying(tagsToMask(def.tags ?? []), def.dmgType);
}
