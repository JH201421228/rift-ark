/**
 * 동료 서사 — **한두 문장짜리 내력의 단일 출처** (2026-08-05, 사용자 요청).
 *
 * ★★ 사용자 제보: "동료 탭의 성장 탭에서 각각의 동료에 대한 간단한 서사에 대한
 *   설명이 있으면 좋을 것 같다." 로스터가 오십 종인데 화면이 말해 주는 것은
 *   수치와 역할뿐이라, 편성 화면에서 동료가 **숫자 묶음**으로만 읽혔다.
 *
 * ★ 문장은 `data/unitLore.json` 에만 있다. 여기에 사본을 두지 않는다 —
 *   이 저장소가 반복해서 겪은 실패 형태가 "같은 사실이 두 곳에 적혀 있다"이고
 *   (역할 목록 · 추천 편성 · 확정 지급 목록), 갈라진 쪽은 늘 화면이었다.
 *
 * ★ `units.json` 의 한 줄 `flavor` 와 **다른 것**이다.
 *   flavor 는 카드에 붙는 표어이고, 여기 있는 것은 그 동료가 어디서 왔는가다.
 *   화면이 둘을 같이 그려도 겹치지 않도록 `unitLore.test.js` 가 감시한다.
 *
 * ★ 순수 모듈이다. `Math.random()` · `Date.now()` · DOM 이 없다 (절대 규칙 1).
 *   조회 한 번은 객체 색인이라 `update()` 안에서 불려도 배열을 만들지 않는다
 *   — 다만 이 값은 전투 중에 쓸 것이 아니라 화면용이다 (절대 규칙 7).
 *
 * ★★ **두 언어가 같은 자리에 있다** (2026-08-07). `lore.<id>` 는 이제 문자열이
 *   아니라 `{ ko, en }` 이다 — `ko.json`/`en.json` 을 따로 두면 한쪽에만 문장을
 *   더하는 순간 다른 언어에서 그 동료의 서사 칸이 조용히 빈다. 이 저장소가
 *   반복해서 당한 "같은 사실이 두 곳에 있으면 갈라진다"의 정확한 형태다.
 *   언어를 고르는 것은 `i18n/index.js:pick` **하나**이고, 여기서 `obj[lang]` 를
 *   직접 읽지 않는다 — 폴백 규칙(영어가 비면 한국어)이 두 벌 생기지 않게 한다.
 *
 * ★ `i18n` 을 import 해도 절대 규칙 1 을 어기지 않는다. `pick` 은 순수 데이터
 *   조회이고 Phaser·DOM·난수·시계를 쓰지 않는다. 그리고 이 모듈은 **시뮬레이션이
 *   읽지 않는다** — 전투 결정론은 언어와 무관하다.
 *
 * @see docs/02-design/10-GDD.md §3.2 톤 — 서사는 진지하게, 유닛은 웃기게
 * @see docs/03-tech/29-i18n.md
 */
// ★ `game/logic/` 은 상대 경로 관례다 (별칭은 Vite 전용이라 순수 Node 하네스에서 터진다).
import { pick } from "../../i18n/index.js";
import DATA from "../data/unitLore.json" with { type: "json" };

/**
 * `unitId` → `{ ko, en }`. **읽기 전용으로 다룬다.**
 * ★ 화면이 이 객체를 순회해 목록을 만들지 않는다 — 로스터의 정본은 `units.json` 이고,
 *   여기 순서로 목록을 그리면 "서사가 있는 동료만 보이는" 화면이 생긴다.
 * ★ 사본을 만들지 않는다 (`DATA.lore` 그 자체다). 사본은 언젠가 갈라진다.
 */
export const UNIT_LORE = Object.freeze(DATA.lore);

/**
 * 그 동료의 서사. 없으면 **null** 이다.
 *
 * ★ 빈 문자열로 돌려주지 않는다 — 빈 문자열은 "서사가 없다"와 "서사가 비어 있다"를
 *   구별하지 못해서, 화면이 빈 칸을 그려 놓고도 조용히 통과한다.
 *   null 이면 호출부가 그 칸을 아예 그리지 않는 선택을 할 수 있다.
 *
 * ★ `lang` 은 **선택 인자**다. 안 넘기면 현재 언어를 쓴다 (`pick` 의 기본값) —
 *   화면 호출부 셋(`CompanionsScreen`)이 언어를 알 필요가 없다. 넘기는 쪽은
 *   테스트·검사기처럼 "지금 언어와 무관하게 이 언어를 보고 싶은" 경우뿐이다.
 *
 * @param {string} unitId `units.json` 의 id
 * @param {"ko"|"en"} [lang] 언어를 강제한다. 기본은 현재 언어.
 * @returns {string|null}
 */
export function loreOf(unitId, lang) {
    // ★ 언어 선택과 폴백(영어가 비면 한국어)은 `pick` 하나가 한다. 여기서
    //   `entry[lang]` 을 직접 읽으면 폴백 규칙이 두 벌이 되고 반드시 갈라진다.
    // ★ `UNIT_LORE` 자체가 `{ id: {ko,en} }` 이므로 id 가 곧 `pick` 의 base 다 —
    //   조회할 때마다 임시 객체를 만들지 않는다 (절대 규칙 7).
    // ★ 프로토타입 위생: `loreOf("constructor")` 는 `pick` 안에서 함수를 만나
    //   ①(object 아님) ②(nameKo 없음) ③(문자열 아님)을 모두 지나 "" 로 떨어진다.
    //   빈 문자열은 아래에서 null 이 된다 — 화면이 함수를 그리는 일이 없다.
    const text = pick(UNIT_LORE, unitId, lang);
    return text ? text : null;
}
